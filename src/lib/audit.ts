// СППВР v2.1 — Audit log helper with hash-chain integrity (WORM)
// ============================================================================
// Every audit log entry is linked to the previous one via `prevHash`, and
// carries its own `hash` = SHA-256(prevHash || canonical(fields)). This makes
// tampering detectable: modifying or deleting any row breaks the chain and
// the verification walk will flag the divergence.
//
// Compliance:
//   - ФЗ-152 ст. 18 ч. 3 (protection of PДn against unauthorized modification)
//   - HIPAA §164.312(c)(1) (data integrity)
//   - HIPAA §164.312(b) (audit controls)
//
// The audit log is append-only: there is no update/delete code path. Rows
// can only be archived by a DBA outside the application, and that archival
// operation is itself audited.

import { createHash } from "crypto";
import { db } from "./db";
import { logger } from "./logger";

export interface AuditEntry {
  action: string;
  details?: Record<string, unknown> | string;
  caseId?: string | null;
  doctorId?: string | null;
  ipAddress?: string | null;
  userAgent?: string | null;
}

/**
 * Compute the SHA-256 hash of a row's canonical content, chained to the
 * previous row's hash.
 *
 * Canonical form (deterministic, order-stable):
 *   `action|details|caseId|doctorId|ipAddress|userAgent|createdAtIso|prevHash`
 */
function computeHash(
  entry: {
    action: string;
    details: string;
    caseId: string | null;
    doctorId: string | null;
    ipAddress: string | null;
    userAgent: string | null;
    createdAt: Date;
  },
  prevHash: string | null,
): string {
  const canonical = [
    entry.action,
    entry.details,
    entry.caseId ?? "",
    entry.doctorId ?? "",
    entry.ipAddress ?? "",
    entry.userAgent ?? "",
    entry.createdAt.toISOString(),
    prevHash ?? "",
  ].join("|");
  return createHash("sha256").update(canonical, "utf8").digest("hex");
}

/**
 * Append a new audit log entry with hash-chain integrity.
 *
 * This is the ONLY function that should be used to create audit log rows.
 * Direct `db.auditLog.create()` calls elsewhere bypass the chain and are
 * considered a defect.
 *
 * v2.7.2 (audit fix): запись сериализована через мьютекс (promise-очередь).
 * Раньше «прочитать последний hash → создать строку» выполнялось двумя
 * независимыми запросами — при конкурентных вызовах оба чтения видели один и
 * тот же prevHash, и вторая строка разрывала цепочку (инцидент 2026-09-08:
 * patient.update записался с чужим prevHash). Очередь гарантирует атомарность
 * пары «чтение-запись» в рамках одного процесса Next.js.
 */
let auditQueue: Promise<unknown> = Promise.resolve();

export function appendAudit(entry: AuditEntry): Promise<void> {
  const run = auditQueue.then(() => appendAuditLocked(entry));
  // Не даём отказавшей вставке «сломать» очередь для последующих записей.
  auditQueue = run.catch(() => {});
  return run;
}

async function appendAuditLocked(entry: AuditEntry): Promise<void> {
  try {
    // Fetch the most recent row's hash to chain against.
    // We order by createdAt desc AND by id desc as a tiebreaker for rows
    // created within the same millisecond.
    const last = await db.auditLog.findFirst({
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      select: { hash: true },
    });
    const prevHash = last?.hash ?? null;

    const now = new Date();
    const detailsStr =
      typeof entry.details === "string"
        ? entry.details
        : JSON.stringify(entry.details ?? {});

    // We need the final `id` to compute a fully stable hash, but the id is
    // generated by the DB (cuid) at insert time. To keep the chain verifiable
    // WITHOUT depending on the id, we hash only the semantic fields + prevHash.
    // The id is still stored and unique, but it is NOT part of the hash —
    // this lets us recompute and verify the chain even if ids change during
    // a legitimate migration.
    const hash = computeHash(
      {
        action: entry.action,
        details: detailsStr,
        caseId: entry.caseId ?? null,
        doctorId: entry.doctorId ?? null,
        ipAddress: entry.ipAddress ?? null,
        userAgent: entry.userAgent ?? null,
        createdAt: now,
      },
      prevHash,
    );

    await db.auditLog.create({
      data: {
        action: entry.action,
        details: detailsStr,
        caseId: entry.caseId ?? null,
        doctorId: entry.doctorId ?? null,
        ipAddress: entry.ipAddress ?? null,
        userAgent: entry.userAgent ?? null,
        prevHash,
        hash,
        createdAt: now,
      },
    });
  } catch (error) {
    // Audit logging must NEVER break the request flow — if it fails, we log
    // the error and continue. The hash-chain integrity is best-effort within
    // a single SQLite writer; concurrent writers could theoretically race,
    // but SQLite serializes writes so this is safe in practice.
    logger.error("audit", "Failed to append audit log entry", {
      action: entry.action,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

/**
 * Verify the integrity of the audit log hash-chain.
 * Returns the first broken link, or null if the chain is intact.
 *
 * This is intended for periodic compliance checks (e.g. a daily cron) and
 * for the admin "Verify integrity" button.
 */
export async function verifyAuditChain(options?: {
  limit?: number;
}): Promise<{
  ok: boolean;
  verified: number;
  /** true, если проверка остановилась на заданном limit и не дошла до конца журнала. */
  truncated: boolean;
  brokenAt: { id: string; expectedHash: string; actualHash: string } | null;
}> {
  const limit = options?.limit ?? 0; // 0 = весь журнал без ограничения
  const BATCH = 500;

  let prevHash: string | null = null;
  let verified = 0;
  let cursor: { createdAt: Date; id: string } | undefined;

  // Курсорная пагинация (батчами) вместо загрузки всего журнала в память:
  // хеш-цепочка проверяется последовательно, перенося prevHash между батчами.
  while (true) {
    const rows = await db.auditLog.findMany({
      orderBy: [{ createdAt: "asc" }, { id: "asc" }],
      take: BATCH,
      ...(cursor ? { cursor, skip: 1 } : {}),
      select: {
        id: true,
        action: true,
        details: true,
        caseId: true,
        doctorId: true,
        ipAddress: true,
        userAgent: true,
        createdAt: true,
        prevHash: true,
        hash: true,
      },
    });
    if (rows.length === 0) break;

    for (const row of rows) {
      const expected = computeHash(
        {
          action: row.action,
          details: row.details,
          caseId: row.caseId,
          doctorId: row.doctorId,
          ipAddress: row.ipAddress,
          userAgent: row.userAgent,
          createdAt: row.createdAt,
        },
        prevHash,
      );
      if (expected !== row.hash || row.prevHash !== prevHash) {
        return {
          ok: false,
          verified,
          truncated: false,
          brokenAt: { id: row.id, expectedHash: expected, actualHash: row.hash },
        };
      }
      prevHash = row.hash;
      verified++;
      if (limit > 0 && verified >= limit) {
        return { ok: true, verified, truncated: true, brokenAt: null };
      }
    }

    const last = rows[rows.length - 1];
    cursor = { createdAt: last.createdAt, id: last.id };
  }

  return { ok: true, verified, truncated: false, brokenAt: null };
}

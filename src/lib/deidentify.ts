// СППВР — модуль де-идентификации (ФЗ-152)
// Полностью локальная замена ФИО, СНИЛС, адресов, телефонов, номеров полисов,
// паспортов, ИНН, email, дат и других PHI на токены перед передачей в ИИ.
//
// ВАЖНО: этот модуль НЕ отправляет данные в облако. Все распознавание
// выполняется локально регулярными выражениями. Это требование ФЗ-152
// ст. 18 ч. 3 — персональные данные не должны покидать периметр
// информационной системы без обезличивания.

export interface DeidResult {
  text: string;
  replacements: Array<{
    type: string;
    original: string;
    token: string;
    count: number;
  }>;
}

// ---------------------------------------------------------------------------
// Паттерны персональных данных (российский + международный форматы)
// ---------------------------------------------------------------------------
// Порядок важен: сначала узкие структурированные паттерны (СНИЛС, ОМС,
// паспорт), потом широкие (даты, адреса), затем ФИО — чтобы не «съесть»
// часть структурированного идентификатора как ФИО.

const PATTERNS: Array<{ type: string; regex: RegExp; token: string }> = [
  // СНИЛС: XXX-XXX-XXX YY или XXXXXXXXXXX YY
  { type: "СНИЛС", regex: /\b\d{3}-\d{3}-\d{3}\s?\d{2}\b/g, token: "[СНИЛС]" },
  // Полис ОМС (16 цифр) — должен идти ДО паспорта и ИНН, чтобы не путать
  { type: "Полис ОМС", regex: /\b\d{16}\b/g, token: "[ПОЛИС]" },
  // Паспорт РФ: серия + номер (XXXX XXXXXX или XXXXXXXXXX)
  { type: "Паспорт", regex: /\b\d{4}\s?\d{6}\b/g, token: "[ПАСПОРТ]" },
  // ИНН (10 или 12 цифр)
  { type: "ИНН", regex: /\b\d{10}(?:\d{2})?\b/g, token: "[ИНН]" },
  // Телефоны: +7 (XXX) XXX-XX-XX, 8XXXXXXXXXX, +7 XXX XXX-XX-XX
  {
    type: "Телефон",
    regex: /(?:\+7|8)[\s(]*\d{3}[)\s-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}\b/g,
    token: "[ТЕЛЕФОН]",
  },
  // Email
  { type: "Email", regex: /\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b/g, token: "[EMAIL]" },
  // v2.3.2 FIX: Ранее ВСЕ даты (включая даты анализов, выписок, операций)
  // заменялись на [ДАТА]. Это ломало клинический анализ — ИИ не видел, когда
  // был сдан анализ или проведена операция. Теперь различаем:
  //   - ДАТА РОЖДЕНИЯ (PHI) → заменяем на [ДАТА_РОЖ] (только если рядом контекст
  //     «родился|рождения|DOB|дата рождения|г.р.»)
  //   - КЛИНИЧЕСКИЕ ДАТЫ (даты анализов, операций, выписок) — СОХРАНЯЕМ.
  //     Это медицинская информация, а не PHI. ФЗ-152 защищает персональные
  //     данные, а даты медицинских событий — это клинические данные.
  // Используем функцию замены с capture group: сохраняем контекст (слово
  // «родился» и т.п.), заменяем только саму дату.
  {
    type: "Дата рождения",
    regex: /((?:дата\s+(?:рождения|рож\.?)|год\s+(?:рождения|рож\.?)|born|DOB|г\.?\s*р\.?)\s*[:\-—]?\s*)(\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}|\d{4}-\d{2}-\d{2})/gi,
    token: "$1[ДАТА_РОЖ]",
  },
  // Также: дата после слова «родился/родилась»
  {
    type: "Дата рождения",
    regex: /(родился(?:ась|ся)?\s+)(\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4})/gi,
    token: "$1[ДАТА_РОЖ]",
  },
  // Индексы (6 цифр подряд, отдельным словом)
  { type: "Индекс", regex: /\b\d{6}\b/g, token: "[ИНДЕКС]" },
  // Адреса: г. ..., ул. ..., д. ... (русскоязычный формат)
  {
    type: "Адрес",
    regex: /(?:г|гор|обл|респ)\.?\s*[А-Яа-яЁё\s-]+,?\s*(?:ул|пр-т|пр|пер|б-р|ш|пл)\.?\s*[А-Яа-яЁё\s-]+,?\s*(?:д|дом|корп|стр|кв|офис)\.?\s*\d+[^\n.,;]*/g,
    token: "[АДРЕС]",
  },
  // Номер медицинской карты / истории болезни
  {
    type: "Номер карты",
    regex: /(?:история\s+болезни|медицинская\s+карта|карта\s+пациента|№\s*истории)\s*[:№]?\s*[А-ЯA-Z0-9-]{3,}/gi,
    token: "[НОМЕР_КАРТЫ]",
  },
  // Номер договора/полиса (буквы + цифры, 6+ символов)
  {
    type: "Номер документа",
    regex: /\b(?:договор|полис|свидетельство)\s*[:№]?\s*[А-ЯA-Z]{0,4}[-]?\d{4,}\b/gi,
    token: "[НОМЕР_ДОКУМЕНТА]",
  },
];

// ---------------------------------------------------------------------------
// ФИО (русскоязычные)
// ---------------------------------------------------------------------------
// Соглашение: "Пациент: Иванов Иван Иванович" -> "Пациент: [ПАЦИЕНТ]"
// Сначала ФИО с явным префиксом (точное распознавание), затем ФИО в формате
// "Фамилия И.О." (инициалы), затем полные ФИО из 2-3 слов с заглавной буквы
// в начале строки (последнее — только с префиксом, иначе слишком много
// ложных срабатываний).

const FIO_PREFIXES =
  "(?:Пациент|Больной|ФИО|Ф\\.?И\\.?О\\.?|Обследуемый|Больной|Заболевший|Госпитализированный|Куратор|Лечащий врач)";
const FIO_PATTERN = new RegExp(
  `(${FIO_PREFIXES})[:\\s]+([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\\s+[А-ЯЁ][а-яё]+(?:\\s+[А-ЯЁ][а-яё]+)?)`,
  "g",
);

// Краткое ФИО: "Иванов И.И." или "Иванов И. И."
const SHORT_FIO = /\b([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?)\s+([А-ЯЁ])\.[\\s]*([А-ЯЁ])\./g;

// ФИО после слова "врач": "лечащий врач Петров А.С."
const DOCTOR_FIO = /(?:врач|куратор|консультант)[:\\s]+([А-ЯЁ][а-яё]+(?:\\s+[А-ЯЁ][а-яё]+){0,2})/g;

export function deidentifyText(raw: string): DeidResult {
  let text = raw;
  const replacements: DeidResult["replacements"] = [];

  // 1. Структурированные паттерны (порядок важен)
  for (const p of PATTERNS) {
    // Сбрасываем lastIndex на случай global regex
    p.regex.lastIndex = 0;
    const matches = text.match(p.regex);
    if (matches && matches.length > 0) {
      const count = matches.length;
      p.regex.lastIndex = 0;
      text = text.replace(p.regex, p.token);
      replacements.push({
        type: p.type,
        original: matches[0],
        token: p.token,
        count,
      });
    }
  }

  // 2. ФИО с префиксом
  FIO_PATTERN.lastIndex = 0;
  const fioMatches = text.match(FIO_PATTERN);
  if (fioMatches) {
    text = text.replace(FIO_PATTERN, "$1: [ПАЦИЕНТ]");
    replacements.push({
      type: "ФИО",
      original: fioMatches[0],
      token: "[ПАЦИЕНТ]",
      count: fioMatches.length,
    });
  }

  // 3. Короткие ФИО "Иванов И.И."
  SHORT_FIO.lastIndex = 0;
  const shortFioMatches = text.match(SHORT_FIO);
  if (shortFioMatches) {
    text = text.replace(SHORT_FIO, "[ПАЦИЕНТ]");
    replacements.push({
      type: "ФИО (кратко)",
      original: shortFioMatches[0],
      token: "[ПАЦИЕНТ]",
      count: shortFioMatches.length,
    });
  }

  // 4. ФИО врача после ключевого слова
  DOCTOR_FIO.lastIndex = 0;
  const doctorMatches = text.match(DOCTOR_FIO);
  if (doctorMatches) {
    text = text.replace(DOCTOR_FIO, "$1: [ВРАЧ]");
    replacements.push({
      type: "ФИО врача",
      original: doctorMatches[0],
      token: "[ВРАЧ]",
      count: doctorMatches.length,
    });
  }

  return { text, replacements };
}

/// Быстрая проверка, содержит ли текст персональные данные
export function containsPHI(text: string): boolean {
  for (const p of PATTERNS) {
    p.regex.lastIndex = 0;
    if (p.regex.test(text)) return true;
  }
  return false;
}

/// Сводка по де-идентификации для отображения в UI
export function deidSummary(result: DeidResult): string {
  if (result.replacements.length === 0) {
    return "Персональные данные не обнаружены";
  }
  return result.replacements.map((r) => `${r.type}: ${r.count}`).join(", ");
}

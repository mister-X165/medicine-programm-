/**
 * Категории клинических рекомендаций.
 * Должны совпадать с полями модели ClinicalRecommendation в Prisma-схеме.
 */
export type RecommendationCategory =
  | "oncology"
  | "cardiology"
  | "pharmacogenomics"
  | "rare_diseases";

/**
 * Уровень доказательности рекомендации.
 * A — высокий (РКИ/мета-анализы), B — умеренный, C — низкий / мнение экспертов.
 */
export type EvidenceLevel = "A" | "B" | "C";

/**
 * Локальный (не Prisma) интерфейс элемента RAG-базы рекомендаций.
 * Используется для типобезопасной инициализации массива seed-данных
 * и для последующей вставки в БД через API-роут /api/seed.
 */
export interface ClinicalRecommendationSeed {
  /** Краткий заголовок рекомендации */
  title: string;
  /** Категория: онкология, кардиология, фармакогеномика, редкие заболевания */
  category: RecommendationCategory;
  /** Символ гена (HUGO): BRCA1, EGFR, CYP2D6 и т.д. */
  gene: string | null;
  /** Конкретный вариант / аллель / комбинация (напр. "V600E", "*2/*2", "p.Phe508del") */
  mutation: string | null;
  /** Полный текст рекомендации */
  content: string;
  /** Ключевые слова для поиска через RAG (через запятую) */
  keywords: string;
  /** Источник: протокол / гайд / клинические рекомендации */
  source: string;
  /** Уровень доказательности: A | B | C */
  evidenceLevel: EvidenceLevel;
}

